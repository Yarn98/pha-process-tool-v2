const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'data/vent_guide.json'), 'utf8'));
if (source.kb_id !== 'pha-kb-16' || !source.version || !source.review_version || !Array.isArray(source.symptoms)) {
  throw new Error('Expected a versioned pha-kb-16 vent guide');
}
const expected = '/* Generated by scripts/sync-vent-guide.cjs from data/vent_guide.json. */\n' +
  '(function (root, factory) {\n' +
  '  const data = factory();\n' +
  '  if (typeof module === "object" && module.exports) module.exports = data;\n' +
  '  if (root) root.PHAVentGuideData = data;\n' +
  '})(typeof window !== "undefined" ? window : null, function () {\n' +
  '  return ' + JSON.stringify(source, null, 2) + ';\n' +
  '});\n';
const target = path.join(root, 'vent-guide-data.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected) {
    throw new Error('Stale vent guide: run node scripts/sync-vent-guide.cjs');
  }
} else {
  fs.writeFileSync(target, expected);
}
console.log('VENT_GUIDE_DATA_OK', source.version, source.vents.length, source.configurations.length, source.symptoms.length);
