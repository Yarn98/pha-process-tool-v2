const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),check=process.argv.includes('--check');
const read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const spec=read('data/troubleshooting_visuals.json'),kb=read('data/troubleshooting_kb.json');
// A cache/content identity, not an authentication hash. Ignore media links.
const fields=['id','review_version','symptom','symptom_ko','likely_causes','likely_causes_ko','diagnostics','diagnostics_ko','quick_fixes','quick_fixes_ko','root_fixes','root_fixes_ko','stop_conditions','stop_conditions_ko'];
function signature(item){const text=JSON.stringify(fields.map(f=>item[f]));let n=2166136261;for(let i=0;i<text.length;i++)n=Math.imul(n^text.charCodeAt(i),16777619);return (n>>>0).toString(16);}
const assets=new Set(['data/troubleshooting_visuals.json','data/troubleshooting_kb.json']);
for(const entry of spec.entries){
  const item=kb.find(x=>x.id===entry.kb_id);if(!item)throw new Error('Unknown KB '+entry.kb_id);
  if(item.review_version!==(entry.kb_review_version||spec.kb_review_version))throw new Error('KB review mismatch '+item.id);
  entry.kb_signature=signature(item);
  entry.model='assets/troubleshooting/'+entry.family+'.glb';assets.add(entry.model);
  entry.thumbnail='assets/troubleshooting/'+entry.kb_id+'-thumb.webp';assets.add(entry.thumbnail);
  const manifest=read('art/troubleshooting/'+entry.family+'-manifest.json');
  entry.states=manifest.states.map(s=>s.state);
  for(const state of entry.states)assets.add('assets/troubleshooting/'+entry.family+'-'+state+'.webp');
  for(const c of entry.cases){
    for(const state of [c.normal,c.state])if(!entry.states.includes(state+'_full'))throw new Error('Missing Blender group '+entry.family+'/'+state);
    if(c.section&&!entry.states.includes(c.state+'_section'))throw new Error('Missing section '+c.id);
    if(c.image)assets.add('assets/troubleshooting/'+c.image+'-example.webp');
  }
}
for(const asset of assets)if(!fs.existsSync(path.join(root,asset)))throw new Error('Missing asset '+asset);
const generated='/* Generated by scripts/sync-troubleshooting-visuals.cjs. */\nwindow.PHATroubleVisualData = '+JSON.stringify(spec,null,2)+';\n';
const sw='/* Generated list; same release as the visual data. */\nself.PHA_TS_VISUAL_ASSETS = '+JSON.stringify([...assets].sort(),null,2)+';\n';
for(const [file,content] of [['data/troubleshooting_visuals.json',JSON.stringify(spec,null,2)+'\n'],['troubleshooting-visuals-data.js',generated],['troubleshooting-visuals-sw.js',sw]]){
  if(check){if(fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n')!==content)throw new Error('Stale '+file);}
  else fs.writeFileSync(path.join(root,file),content);
}
console.log('TROUBLE_VISUAL_DATA_OK',spec.entries.length,spec.entries.flatMap(x=>x.cases).length,assets.size);
module.exports={signature,fields};
