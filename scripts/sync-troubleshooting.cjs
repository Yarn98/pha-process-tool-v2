const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'data/troubleshooting_kb.json'), 'utf8'));
if (!Array.isArray(source) || !source.length) throw new Error('Expected a nonempty troubleshooting array');
const expected = '/* Generated by scripts/sync-troubleshooting.cjs from data/troubleshooting_kb.json. */\nwindow.PHA_TROUBLESHOOTING_DATA = ' + JSON.stringify(source, null, 2) + ';\n';
const target = path.join(root, 'troubleshooting-data.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected) throw new Error('Stale offline KB: run node scripts/sync-troubleshooting.cjs');
} else fs.writeFileSync(target, expected);
console.log('Troubleshooting JSON and offline data agree: ' + source.length + ' entries');
