const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const read = rel => JSON.parse(fs.readFileSync(path.join(root, rel), 'utf8'));
const ref = read('data/crystallization/p3hb_ref_2026.json');
const presets = read('data/process/crystallization_presets.json');
if (ref.id !== 'P3HB_REF_2026' || !ref.engine || !presets.version || !presets.grades) {
  throw new Error('Expected P3HB_REF_2026 reference and versioned crystallization presets');
}
const source = { reference: { P3HB_REF_2026: ref }, presets };
const expected = '/* Generated by scripts/sync-crystallization.cjs from data/crystallization/p3hb_ref_2026.json and data/process/crystallization_presets.json. */\n' +
  '(function (root, factory) {\n' +
  '  const data = factory();\n' +
  '  if (typeof module === "object" && module.exports) module.exports = data;\n' +
  '  if (root) root.PHACrystalData = data;\n' +
  '})(typeof window !== "undefined" ? window : null, function () {\n' +
  '  return ' + JSON.stringify(source, null, 2) + ';\n' +
  '});\n';
const target = path.join(root, 'crystallization-data.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected) {
    throw new Error('Stale crystallization data: run node scripts/sync-crystallization.cjs');
  }
} else {
  fs.writeFileSync(target, expected);
}
console.log('CRYSTAL_DATA_OK', presets.version, Object.keys(presets.grades).length, presets.conflicts.length);
